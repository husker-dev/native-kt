package com.huskerdev.nativekt.printers.objc

import com.huskerdev.nativekt.*
import com.huskerdev.nativekt.utils.*
import com.huskerdev.stdlibx.fs.SyncPath
import com.huskerdev.stdlibx.systemLineSeparator

class ObjcApiHeaderPrinter(
    val context: NativeModuleContext,
    target: SyncPath
) {
    init {
        target.parent!!.createDirectories()
        target.writeString(buildString {
            printHeader()
            printTypeDefs()
            printStdLib()
            printEnums()
            printInterfaces()
            printCallbacks()
            printStructs()
            printFunctions()
        }.replace("\n", systemLineSeparator))
    }

    private fun StringBuilder.printHeader() {
        appendLine("""
            /*
             * This file was automatically generated by native-kt.
             *
             * DO NOT EDIT THIS FILE MANUALLY.
             * Any changes made to this file will be overwritten the next time
             * the project is built.
             */

            #pragma once

            #import <Foundation/Foundation.h>
            #import <stdint.h>
            #include <stdbool.h>

            #if !__has_feature(objc_arc)
            #error native-kt Objective-C bindings require ARC (-fobjc-arc)
            #endif
        """.trimIndent())
    }

    private fun StringBuilder.printTypeDefs() {
        if (context.castedCallbacks.isEmpty() &&
            context.dictionaries.isEmpty() &&
            context.interfaces.isEmpty()
        ) return
        printLabel("Type definitions")

        buildList {
            addAll(context.dictionaries)
            addAll(context.interfaces)
            addAll(context.castedCallbacks)
        }.joinTo(this, separator = "") {
            "\n@class ${it.objcName};"
        }
        append("\n")
    }

    private fun StringBuilder.printStdLib() {
        if (!context.hasString &&
            !context.hasObjectArrays &&
            !context.hasPrimitiveArray &&
            !context.hasEnumArray &&
            !context.hasPrimitiveNullableArray &&
            !context.hasEnumNullableArray
        ) return
        printLabel("Types")

        if (context.hasString) appendLine("""

            ${objcRuntimeName(context, "KTString")}
            @interface KTString : NSObject <NSCopying>
            @property (nonatomic, readonly) const char* _Nullable data;
            @property (nonatomic, readonly) size_t size;

            - (instancetype _Nonnull)initWithBytes:(const char* _Nullable)bytes size:(size_t)size;
            - (instancetype _Nonnull)initWithBytes:(const char* _Nullable)bytes size:(size_t)size makeCopy:(BOOL)makeCopy;
            - (instancetype _Nonnull)initWithNSString:(NSString* _Nonnull)string;
            - (NSString* _Nullable)toNSString;
            @end
        """.trimIndent())
        if (context.hasPrimitiveArray || context.hasEnumArray) {
            appendLine("""

                ${objcRuntimeName(context, "KTPrimitiveArray")}
                @interface KTPrimitiveArray : NSObject <NSCopying>
                @property (nonatomic, readonly) const void* _Nullable data;
                @property (nonatomic, readonly) int32_t length;

                - (NSArray<NSNumber*>* _Nonnull)toNSArray;
                @end
            """.trimIndent())
            context.objcPrimitiveArrayTypes().forEach { (name, type) ->
                appendLine("""

                    ${objcRuntimeName(context, "KT${name}Array")}
                    @interface KT${name}Array : KTPrimitiveArray
                    @property (nonatomic, readonly) const $type* _Nullable elements;

                    - (instancetype _Nonnull)initWithElements:(const $type* _Nullable)elements length:(int32_t)length;
                    - (instancetype _Nonnull)initWithElements:(const $type* _Nullable)elements length:(int32_t)length makeCopy:(BOOL)makeCopy;
                    - (instancetype _Nonnull)initWithNSArray:(NSArray<NSNumber*>* _Nonnull)array;
                    @end
                """.trimIndent())
            }
        }
        if (context.hasObjectArrays || context.hasPrimitiveNullableArray || context.hasEnumNullableArray) appendLine("""

            ${objcRuntimeName(context, "KTArray")}
            @interface KTArray<__covariant ObjectType> : NSObject <NSCopying>
            @property (nonatomic, readonly) int32_t length;
            @property (nonatomic, readonly, copy) NSArray<ObjectType>* _Nonnull elements;

            - (instancetype _Nonnull)initWithCapacity:(int32_t)capacity;
            - (instancetype _Nonnull)initWithNSArray:(NSArray* _Nonnull)array;
            - (NSArray* _Nonnull)toNSArray;
            - (ObjectType _Nonnull)objectAtIndexedSubscript:(NSUInteger)index;
            - (void)addObject:(ObjectType _Nonnull)object;
            @end
        """.trimIndent())
    }

    private fun StringBuilder.printEnums() {
        if (context.enums.isEmpty())
            return
        printLabel("Enums")

        context.enums.forEach { enum ->
            printCLikeComment(enum.leadingComments)
            append("\ntypedef NS_ENUM(int32_t, ${enum.objcName}) {")

            enum.elements.forEachIndexed { index, element ->
                printCLikeComment(enum.elementComments[element]!!, indent = "\t")
                append("\n\t${enum.objcName}_$element = $index")
                if(index != enum.elements.lastIndex)
                    append(",")
            }
            append("\n};\n")
        }
    }

    private fun StringBuilder.printInterfaces() {
        if (context.interfaces.isEmpty())
            return
        printLabel("Interfaces")

        context.interfaces.forEach { inter ->
            val interName = inter.objcName

            printCLikeComment(inter.leadingComments)
            append("""

                ${objcRuntimeName(context, interName)}
                @interface $interName : NSObject
            """.trimIndent())
            context.interfaceOperations[inter]!!.forEach { operation ->
                val funcName = operation.objcName
                val args = operation.args.map { it.objcName to it.type.toObjcType() }
                val type = operation.type.toObjcType()

                printCLikeComment(operation.leadingComments)
                when {
                    operation.isInterfaceOperationConstructor() ->
                        append("\n+ (instancetype _Nonnull)${objcMethod(funcName, args)};")
                    operation.isInterfaceOperationFn() ->
                        append("\n- ($type)${objcMethod(funcName, args.drop(1))};")
                }
            }
            append("\n@end\n")
        }
    }

    private fun StringBuilder.printCallbacks() {
        if (!context.hasCallback)
            return
        printLabel("Callbacks")

        context.castedCallbacks.forEach { callback ->
            val callbackName = callback.objcName
            val args = callback.args.map { it.objcName to it.type.toObjcType() }
            val type = callback.type.toObjcType()

            printCLikeComment(callback.leadingComments)
            appendLine("""

                ${objcRuntimeName(context, callbackName)}
                @interface $callbackName : NSObject
                - ($type)${objcMethod("invoke", args)};
                @end
            """.trimIndent())
        }
        append("\n")
    }

    private fun StringBuilder.printStructs() {
        if (context.dictionaries.isEmpty())
            return
        printLabel("Dictionaries")

        context.dictionaries.sortedWith { first, second ->
            when {
                first == second.implements -> -1
                first.implements == second -> 1
                else -> first.name.compareTo(second.name)
            }
        }.forEach { dictionary ->
            val dictName = dictionary.objcName
            val parent = dictionary.implements?.objcName ?: "NSObject"
            val localFields = dictionary.fields
            val allFields = context.allFields[dictionary]!!

            printCLikeComment(dictionary.leadingComments)
            append("""

                ${objcRuntimeName(context, dictName)}
                @interface $dictName : $parent
            """.trimIndent())

            // Fields
            localFields.forEach { field ->
                val ownership = if (field.type.isObjcObject()) "strong" else "assign"
                printCLikeComment(field.leadingComments)
                append("\n@property (nonatomic, $ownership) ${field.type.toObjcType()} ${field.objcName};")
            }

            // Constructor
            if (allFields.isNotEmpty()) {
                val constructorName = "initWith${allFields.first().objcName.uppercaseFirstChar()}"
                val constructorArgs = allFields.map { it.objcName to it.type.toObjcType() }
                append("\n- (instancetype _Nonnull)${objcMethod(constructorName, constructorArgs)};")
            }
            append("\n@end\n")
        }
    }

    private fun StringBuilder.printFunctions() {
        if (context.operations.isEmpty())
            return
        printLabel("Functions")

        append("""

            ${objcRuntimeName(context, "NativeKt")}
            @interface NativeKt : NSObject
            @end

            @interface NativeKt (API)
        """.trimIndent())
        context.operations.forEach { operation ->
            val args = operation.args.map { it.objcName to it.type.toObjcType() }
            printCLikeComment(operation.leadingComments)
            append("\n+ (${operation.type.toObjcType()})${objcMethod(operation.objcName, args)};")
        }
        append("\n@end")
    }
}
